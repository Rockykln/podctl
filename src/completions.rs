//! Shell completions, written out from the command table so names,
//! aliases and values cannot drift apart from the parser.

use crate::commands::{self, Cmd};

pub const SHELLS: &[&str] = &["bash", "zsh", "fish"];

pub fn script(shell: &str) -> Option<String> {
    match shell {
        "bash" => Some(bash()),
        "zsh" => Some(zsh()),
        "fish" => Some(fish()),
        _ => None,
    }
}

/// Every spelling of a verb, for the `case` patterns.
fn patterns(c: &Cmd) -> String {
    let mut all = vec![c.name];
    all.extend_from_slice(c.aliases);
    all.join("|")
}

/// What to offer at argument `pos` (1-based) of a verb: its values, plus
/// the verb's own options.
fn words_at(c: &Cmd, pos: usize) -> Vec<&'static str> {
    let mut out: Vec<&'static str> = c.values_at(pos - 1).to_vec();
    if c.name == "help" && pos == 1 {
        out = commands::COMMANDS.iter().map(|c| c.name).collect();
    }
    out.extend_from_slice(c.flags);
    out
}

fn max_pos(c: &Cmd) -> usize {
    c.max_args().max(1)
}

const GENERATED: &str = "# Generated by 'podctl completion' from the command table.\n";

/// `_init_completion` comes from the bash-completion package, which a
/// minimal system may not have loaded: without the fallback the whole
/// function died with "command not found".
const BASH_HEAD: &str = r#"_podctl() {
    local cur words cword
    if declare -F _init_completion >/dev/null 2>&1; then
        _init_completion || return
    else
        cur="${COMP_WORDS[COMP_CWORD]}"
        words=("${COMP_WORDS[@]}")
        cword=$COMP_CWORD
    fi

"#;

fn bash() -> String {
    let mut s = String::from(GENERATED);
    s.push_str(BASH_HEAD);
    s.push_str(&format!(
        "    local cmds=\"{}\"\n\n",
        commands::words().join(" ")
    ));
    // The verb is the first word that is not an option: `podctl --json
    // mode <TAB>` used to look at "--json" and offer nothing.
    s.push_str(
        "    local i vi=0 verb=\"\"\n    for ((i = 1; i < cword; i++)); do\n        \
         if [[ ${words[i]} != -* ]]; then verb=\"${words[i]}\"; vi=$i; break; fi\n    done\n\n    \
         if [[ -z $verb ]]; then\n        COMPREPLY=( $(compgen -W \"$cmds --json --pretty --help --version\" -- \"$cur\") )\n        \
         return\n    fi\n\n    local argpos=$(( cword - vi ))\n    case \"$verb\" in\n",
    );
    for c in commands::COMMANDS {
        let mut arms = String::new();
        for pos in 1..=max_pos(c) {
            let words = words_at(c, pos);
            if words.is_empty() {
                continue;
            }
            arms.push_str(&format!(
                "            {pos}) COMPREPLY=( $(compgen -W \"{}\" -- \"$cur\") );;\n",
                words.join(" ")
            ));
        }
        // Options stay on offer after the first one: `podctl install
        // --yes --<TAB>` is past the last positional slot.
        if !c.flags.is_empty() {
            arms.push_str(&format!(
                "            *) COMPREPLY=( $(compgen -W \"{}\" -- \"$cur\") );;\n",
                c.flags.join(" ")
            ));
        }
        if arms.is_empty() {
            continue;
        }
        s.push_str(&format!("        {})\n", patterns(c)));
        s.push_str("            case $argpos in\n");
        s.push_str(&arms);
        s.push_str("            esac\n            ;;\n");
    }
    s.push_str("    esac\n}\ncomplete -F _podctl podctl\n");
    s
}

fn zsh() -> String {
    let mut s = String::from("#compdef podctl\n");
    s.push_str(GENERATED);
    s.push_str("_podctl() {\n    local -a cmds\n    cmds=(\n");
    for c in commands::COMMANDS {
        s.push_str(&format!(
            "        '{}:{}'\n",
            c.name,
            c.summary.replace('\'', "")
        ));
    }
    s.push_str("    )\n\n    local -a aliases\n    aliases=(\n");
    for c in commands::COMMANDS {
        for a in c.aliases {
            s.push_str(&format!("        '{a}:{}'\n", c.name));
        }
    }
    s.push_str("    )\n\n");
    s.push_str(
        "    local i vi=0 verb=\"\"\n    for (( i = 2; i < CURRENT; i++ )); do\n        \
         if [[ ${words[i]} != -* ]]; then verb=${words[i]}; vi=$i; break; fi\n    done\n\n    \
         if [[ -z $verb ]]; then\n        _describe -t commands 'podctl command' cmds\n        \
         _describe -t aliases 'alias' aliases\n        \
         return\n    fi\n\n    local argpos=$(( CURRENT - vi ))\n    case $verb in\n",
    );
    for c in commands::COMMANDS {
        let mut arms = String::new();
        for pos in 1..=max_pos(c) {
            let words = words_at(c, pos);
            if words.is_empty() {
                continue;
            }
            arms.push_str(&format!(
                "                {pos}) compadd {} ;;\n",
                words.join(" ")
            ));
        }
        if !c.flags.is_empty() {
            arms.push_str(&format!(
                "                *) compadd {} ;;\n",
                c.flags.join(" ")
            ));
        }
        if arms.is_empty() {
            continue;
        }
        s.push_str(&format!("        {})\n", patterns(c)));
        s.push_str("            case $argpos in\n");
        s.push_str(&arms);
        s.push_str("            esac\n            ;;\n");
    }
    s.push_str("    esac\n}\n_podctl \"$@\"\n");
    s
}

fn fish() -> String {
    let mut s = String::from(GENERATED);
    s.push_str("complete -c podctl -f\n");
    for c in commands::COMMANDS {
        s.push_str(&format!(
            "complete -c podctl -n __fish_use_subcommand -a {} -d '{}'\n",
            c.name,
            c.summary.replace('\'', "")
        ));
        for a in c.aliases {
            s.push_str(&format!(
                "complete -c podctl -n __fish_use_subcommand -a {a} -d '{}'\n",
                c.name
            ));
        }
    }
    s.push('\n');
    for c in commands::COMMANDS {
        // Fish has no notion of argument position here, so a verb with
        // two arguments offers both sets.
        let mut words: Vec<&str> = Vec::new();
        for pos in 1..=max_pos(c) {
            words.extend(words_at(c, pos));
        }
        words.dedup();
        if words.is_empty() {
            continue;
        }
        s.push_str(&format!(
            "complete -c podctl -n '__fish_seen_subcommand_from {}' -a '{}'\n",
            patterns(c).replace('|', " "),
            words.join(" ")
        ));
    }
    s
}

#[cfg(test)]
mod tests {
    use super::{SHELLS, script};
    use crate::commands;

    /// Every name and alias has to appear, because the old hand-written
    /// scripts only completed the canonical spelling: `podctl m <TAB>`
    /// and `podctl tone <TAB>` offered nothing.
    #[test]
    fn every_spelling_is_offered() {
        for shell in SHELLS {
            let text = script(shell).expect("known shell");
            for word in commands::words() {
                assert!(text.contains(word), "{shell}: '{word}' missing");
            }
        }
    }

    /// The internal test hook must not be advertised.
    #[test]
    fn the_debug_hook_stays_hidden() {
        for shell in SHELLS {
            let text = script(shell).expect("known shell");
            assert!(!text.contains("emit-case-lid"), "{shell}");
        }
    }

    #[test]
    fn unknown_shell_has_no_script() {
        assert!(script("csh").is_none());
    }
}
